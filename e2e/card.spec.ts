/**
 * Photograph one live card once, in one language, and write it where the README reads it.
 *
 * A context of its own rather than the test's page, for two reasons: the figure's narrow
 * viewport then belongs to the figure instead of to every measurement in this file,
 * which are all written against the configured 1400px; and the shot is taken after
 * WAITING for the language, which must not disturb the test's own page.
 * @param browser - the browser fixture.
 * @param url - the booted host's URL (one per language; see the figure block).
 * @param sessionId - the fixture session to open; each context has its own storage.
 * @param locale - the browser locale, which must AGREE with that host's stored
 *   `locale.preference`. The two are different inputs and either can decide the page
 *   language: the client starts from the browser's and replaces it with the host's once
 *   the plugin activates, and which happens first is not guaranteed — a zh host shot from
 *   an `en-US` context produced an English title on one run and a Chinese one on the
 *   next. Setting both removes the race instead of betting on one side of it.
 * @param callId - the live call whose card is photographed.
 * @param path - where the PNG goes.
 * @param hoverPath - where the hover-card figure goes.
 * @param hoverCallId - the SETTLED call whose segment is hovered for that figure. It is a
 *   different card from `callId` on purpose: a live run's notes come from a model the
 *   fixture host does not have, so a hover figure of the live card would show no note while
 *   the README beside it says there is one. The settled record carries the seeded notes.
 * @param titleText - the title text to WAIT for before shooting: the card's title is the
 *   shell's, and the stored `locale.preference` replaces the client's provisional
 *   browser-derived language once the plugin activates, so the wrong one is on screen
 *   for a moment. A screenshot taken then is a figure of the wrong language.
 * @returns the card's text and its measured width, for the assertions.
 */
async function captureFigure(
  browser: import('@playwright/test').Browser,
  url: string,
  sessionId: string,
  locale: string,
  callId: string,
  path: string,
  hoverPath: string,
  hoverCallId: string,
  titleText: string,
): Promise<{ readonly title: string; readonly width: number }> {
  const context = await browser.newContext({ locale, viewport: { width: README_FIGURE_WIDTH, height: 900 } })
  try {
    const page = await context.newPage()
    await page.addInitScript((id) => {
      localStorage.setItem('dsh.sessions.current', JSON.stringify({ sessionId: id }))
    }, sessionId)
    await page.goto(url, { waitUntil: 'domcontentloaded' })
    const card = page.locator(`[data-chat-call-id="${callId}"]`)
    await expect(card, `the fixture never rendered ${callId}`).toBeAttached({ timeout: 90_000 })
    await expandTranscript(page)
    await revealCard(card)
    // Opened, so the crop carries the bar AND the step list. The click anchors on
    // `shell_progress`, which the title carries in EVERY locale.
    await card.getByText('shell_progress').first().click({ timeout: 10_000 }).catch(() => {})
    await revealCard(card)
    // The shape the figure documents — one step finished, the next in flight — which the
    // run holds for twenty seconds, so neither figure is a race.
    await expect(
      card.locator('[role="progressbar"] [data-phase="running"]'),
      `${callId} never showed a step in flight`,
    ).toHaveCount(1, { timeout: 60_000 })
    // WAIT for the language before shooting: see this helper's `titleText`.
    await expect(card, `${callId}'s card never took its ${titleText} title`).toContainText(titleText, { timeout: 30_000 })
    mkdirSync(dirname(path), { recursive: true })
    await card.screenshot({ path, animations: 'disabled' })
    // The hover figure, from the SETTLED card: its notes are part of the record, and the
    // README says the hover card carries one. A UNION crop, because the card is portaled out
    // of the row (see `README_HOVER_SHOT`) and `card.screenshot` would clip the tooltip away.
    const hoverTarget = page.locator(`[data-chat-call-id="${hoverCallId}"]`)
    await expect(hoverTarget, `the fixture never rendered ${hoverCallId}`).toBeAttached({ timeout: 90_000 })
    // The settled card lives in an EARLIER turn, and the shell may have that turn folded away
    // by the time the live figure has been shot: unfold it and open the card, or its bar is
    // attached but not visible and the hover can never land.
    await expandTranscript(page)
    await hoverTarget.getByText('shell_progress').first().click({ timeout: 10_000 }).catch(() => {})
    await revealCard(hoverTarget)
    // The SECOND segment, not the first: it carries a note, and its card opens INSIDE the
    // card's own area — hovering the first one puts the card above the row and the crop then
    // pulls in whatever card sits above it.
    const hoverSegment = hoverTarget.locator('[role="progressbar"] [data-phase]').nth(1)
    await expect(hoverSegment, `${hoverCallId}'s bar is not on screen`).toBeVisible({ timeout: 10_000 })
    await hoverSegment.hover({ timeout: 10_000 })
    const portal = page.locator('body > div:has(> [data-step-card])').first()
    await expect(portal, `${hoverCallId}'s segment opened no hover card`).toBeVisible({ timeout: 10_000 })
    await expect(
      portal.locator('[data-card-note="true"]'),
      `${hoverCallId}'s hover card shows no note, so the figure would not show one either`,
    ).toBeVisible({ timeout: 10_000 })
    const cardBox = await hoverTarget.boundingBox()
    const portalBox = await portal.boundingBox()
    if (cardBox === null || portalBox === null) throw new Error(`${hoverCallId}: the hover shot has no box to crop to`)
    const pad = 8
    const left = Math.max(0, Math.min(cardBox.x, portalBox.x) - pad)
    const top = Math.max(0, Math.min(cardBox.y, portalBox.y) - pad)
    const right = Math.max(cardBox.x + cardBox.width, portalBox.x + portalBox.width) + pad
    const bottom = Math.max(cardBox.y + cardBox.height, portalBox.y + portalBox.height) + pad
    mkdirSync(dirname(hoverPath), { recursive: true })
    await page.screenshot({
      path: hoverPath,
      clip: { x: left, y: top, width: right - left, height: bottom - top },
      animations: 'disabled',
    })
    const box = await card.boundingBox()
    return { title: (await card.textContent()) ?? '', width: box?.width ?? -1 }
  } finally {
    await context.close()
  }
}

/**
 * Measure one call row: the numbers that decide whether the card is laid out.
 * @param call - the located call row.
 * @returns its box, its segment count and its bar's box.
 */
async function metricsOf(call: import('@playwright/test').Locator): Promise<Metrics> {
  return await call.evaluate((node) => {
    const box = node.getBoundingClientRect()
    const bar = node.querySelector('[role="progressbar"]')
    const barBox = bar === null ? undefined : bar.getBoundingClientRect()
    return {
      top: Math.round(box.top),
      height: Math.round(box.height),
      width: Math.round(box.width),
      segments: node.querySelectorAll('[data-phase]').length,
      barTop: barBox === undefined ? 0 : Math.round(barBox.top),
      barWidth: barBox === undefined ? 0 : Math.round(barBox.width),
      barHeight: barBox === undefined ? 0 : Math.round(barBox.height),
      text: (node.textContent ?? '').slice(0, 200),
    }
  })
}

/**
 * Open whatever the shell has collapsed in the conversation column.
 *
 * Best effort by design: the shell's disclosure controls are not this plugin's
 * contract, so nothing here is asserted. Only elements that ADVERTISE themselves
 * as collapsed are clicked — a blind click flips whatever the toggle currently
 * is, which collapses a transcript that was already open.
 * @param page - the page holding the transcript.
 */
async function expandTranscript(page: import('@playwright/test').Page): Promise<void> {
  for (let round = 0; round < 5; round += 1) {
    const collapsed = page.locator('[aria-expanded="false"]')
    const boxes = await collapsed.evaluateAll((nodes) => nodes.map((node) => {
      const box = node.getBoundingClientRect()
      return { x: box.x, width: box.width, height: box.height }
    }))
    const index = boxes.findIndex((box) => box.width > 0 && box.height > 0 && box.x > 300)
    if (index < 0) return
    await collapsed.nth(index).click({ timeout: 5_000 }).catch(() => {})
    await page.waitForTimeout(150)
  }
}

/**
 * Lift `visibility: hidden` from the card and its ancestors.
 *
 * A collapsed row keeps its layout box, so this only affects whether it PAINTS.
 * The shell's collapse gesture is not under test here; the card is.
 * @param card - the located call row.
 */
async function revealCard(card: import('@playwright/test').Locator): Promise<void> {
  await card.evaluate((node) => {
    let current: Element | null = node
    while (current !== null) {
      const style = getComputedStyle(current)
      const element = current as HTMLElement
      if (style.visibility === 'hidden') element.style.visibility = 'visible'
      if (style.display === 'none') element.style.display = 'block'
      if (style.opacity === '0') element.style.opacity = '1'
      current = current.parentElement
    }
  })
}

/**
 * Wait for one marker line to appear in a log file.
 * @param file - the log to poll.
 * @param marker - the prefix to look for.
 * @param budgetMs - how long to wait.
 * @returns the marker's value, or undefined when it never arrived.
 */
async function waitForMarker(file: string, marker: string, budgetMs: number): Promise<string | undefined> {
  const deadline = Date.now() + budgetMs
  for (;;) {
    if (existsSync(file)) {
      const line = readFileSync(file, 'utf8').split('\n').find((entry) => entry.includes(marker))
      if (line !== undefined) return line.slice(line.indexOf(marker) + marker.length).trim()
    }
    if (Date.now() >= deadline) return undefined
    await sleep(300)
  }
}
